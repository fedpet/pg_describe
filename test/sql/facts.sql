CREATE EXTENSION IF NOT EXISTS pg_describe;
BEGIN;
CREATE SCHEMA facts;
SET search_path=facts,public;
CREATE DOMAIN choice AS text CHECK(VALUE IN('a','b','c')) CHECK(VALUE IN('b','c','d'));
CREATE DOMAIN unsafe_choice AS text CHECK(VALUE IN('a',NULL));
CREATE TABLE sample(id int PRIMARY KEY, x text CHECK(x IN('a','b')), y choice, unsafe unsafe_choice, tags text[] CHECK(tags <@ ARRAY['a','b']));
INSERT INTO sample VALUES(1,'a','b','unrestricted',ARRAY['a']), (2,NULL,NULL,NULL,ARRAY[]::text[]);
SELECT pg_describe_facts('SELECT x,y,unsafe,tags FROM sample')->'columns' AS finite;
SELECT pg_describe_type_facts('choice'::regtype) AS domain;
SELECT pg_describe_type_facts('unsafe_choice'::regtype) AS unsafe_domain;
SELECT pg_describe_facts('SELECT x FROM sample WHERE x IN (''b'',''c'')')->'columns' AS intersection;
SELECT pg_describe_facts('SELECT x FROM sample WHERE x=''a'' OR x=''b''')->'columns' AS alternatives;
SELECT pg_describe_facts('SELECT unsafe FROM sample WHERE unsafe=''a'' OR id=1')->'columns' AS unknown_alternative;
SELECT result_not_null FROM pg_describe('SELECT x FROM sample WHERE x IS NOT NULL');
SELECT result_not_null FROM pg_describe('SELECT x FROM sample WHERE x IS NOT NULL OR id=1');
SELECT result_not_null FROM pg_describe('SELECT max(x) FROM sample WHERE x IS NOT NULL');
SELECT pg_describe_facts('SELECT unsafe FROM sample WHERE unsafe IN (''a'', NULL)')->'columns' AS where_null_member;
SELECT pg_describe_facts('SELECT lower(x) FROM sample')->'columns' AS transformed_unknown;
CREATE TABLE unchecked(x text);
ALTER TABLE unchecked ADD CHECK(x IN('a')) NOT VALID;
SELECT pg_describe_facts('SELECT x FROM unchecked')->'columns' AS unvalidated_unknown;
CREATE TABLE parent(x text CHECK(x IN('a')) NO INHERIT);
CREATE TABLE child() INHERITS(parent);
INSERT INTO child VALUES('b');
SELECT pg_describe_facts('SELECT x FROM parent')->'columns' AS inheritance_unknown;
CREATE FUNCTION volatile_value() RETURNS text VOLATILE LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'must never execute';END$$;
SELECT result_not_null FROM pg_describe('SELECT volatile_value() WHERE volatile_value() IS NOT NULL');
SELECT pg_describe_facts('COPY sample FROM STDIN WITH(FORMAT csv,HEADER true)')->'copy' AS copy_in;
SELECT pg_describe_facts('COPY (SELECT x FROM sample) TO STDOUT WITH(FORMAT binary)')->'copy' AS copy_out;
SELECT pg_describe_facts('COPY sample TO ''/tmp/unused-file''')->'copy' AS server_file;
SELECT pg_describe_facts('COPY sample TO PROGRAM ''must-not-run''')->'copy' AS server_program;
CREATE PROCEDURE outputs(IN x int, INOUT y text, OUT z choice) LANGUAGE plpgsql AS $$BEGIN y:=x::text; z:='b';END$$;
SELECT kind,ord,name,type_name FROM pg_describe('CALL outputs(1,''input'',NULL)');
CALL outputs(1,'input',NULL);
DO $$DECLARE shape jsonb;BEGIN
  SELECT result_shape INTO shape FROM pg_describe('SELECT json_build_object(''value'',x) FROM sample');
  IF shape->'fields'->0->'shape'->'values' IS DISTINCT FROM '["a","b"]'::jsonb THEN RAISE EXCEPTION 'Nested JSON lost its finite value proof';END IF;
END$$;
CREATE COLLATION folded(provider=icu,locale='und-u-ks-level2',deterministic=false);
CREATE TABLE collated(x text COLLATE folded CHECK(x='a'));
INSERT INTO collated VALUES('A');
SELECT pg_describe_facts('SELECT x FROM collated')->'columns' AS collation_unknown;
CREATE TYPE state AS ENUM('first','Second');
CREATE TABLE enums(x state);
SELECT pg_describe_facts('SELECT x FROM enums WHERE x=''Second''')->'columns' AS enum_predicate;
CREATE ROLE facts_restricted;
GRANT USAGE ON SCHEMA facts TO facts_restricted;
REVOKE ALL ON PROCEDURE outputs(int,text) FROM PUBLIC;
REVOKE ALL ON TYPE choice FROM PUBLIC;
SET ROLE facts_restricted;
SAVEPOINT call_permission;
SELECT * FROM public.pg_describe('CALL facts.outputs(1, NULL, NULL)');
ROLLBACK TO call_permission;
SAVEPOINT relation_permission;
SELECT public.pg_describe_facts('SELECT x FROM facts.sample');
ROLLBACK TO relation_permission;
SAVEPOINT type_permission;
SELECT public.pg_describe_type_facts('facts.choice'::regtype);
ROLLBACK TO type_permission;
RESET ROLE;
ROLLBACK;
